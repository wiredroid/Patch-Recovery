#!/usr/bin/env python3
"""Compare stock vs candidate BTF named STRUCT/UNION member layouts.

Inputs: btf_struct_members.tsv files generated by the A146P stock BTF parser
(extracted from the original Samsung firmware and separately from candidate
vmlinux). Do NOT treat a match as binary, KMI, CRC, signature or runtime proof.
"""
import argparse
from collections import Counter, defaultdict
import csv
import json
from pathlib import Path

def parse_layouts(path):
    """Map named kind/name -> all observed size/member signatures.

    Multiple BTF records can share a name. Do not arbitrarily select the first.
    """
    records = defaultdict(lambda: defaultdict(list))
    with path.open(newline="") as f:
        for r in csv.DictReader(f, delimiter="\t"):
            if r["struct_or_union"] not in ("STRUCT", "UNION") or not r["name"]:
                continue
            key = (r["struct_or_union"], r["name"])
            identity = (r["type_id"], int(r["size_bytes"]))
            records[key][identity].append(
                (r["member"], int(r["bit_offset"]), int(r["bitfield_size"]), r["member_type"])
            )
    return {
        name: set((size, tuple(members)) for (_, size), members in variants.items())
        for name, variants in records.items()
    }

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("stock_tsv", type=Path)
    ap.add_argument("candidate_tsv", type=Path)
    ap.add_argument("--out", type=Path, default=Path("btf-layout-audit"))
    ap.add_argument("--prefix", action="append", default=[])
    ap.add_argument("--only", action="append", default=[])
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    stock = parse_layouts(args.stock_tsv)
    candidate = parse_layouts(args.candidate_tsv)
    names = sorted(set(stock) | set(candidate))
    if args.prefix or args.only:
        names = [x for x in names if x[1] in args.only or
                 any(x[1].startswith(pre) for pre in args.prefix)]
    rows = []
    for key in names:
        s, c = stock.get(key, set()), candidate.get(key, set())
        if not s:
            status = "CANDIDATE_ONLY"
        elif not c:
            status = "STOCK_ONLY"
        elif s == c:
            status = "NAMED_MEMBER_LAYOUT_MATCH"
        elif {v[0] for v in s} == {v[0] for v in c}:
            status = "SAME_SIZE_MEMBER_MISMATCH"
        else:
            status = "SIZE_MISMATCH"
        sizes = lambda variants: ",".join(map(str, sorted({v[0] for v in variants})))
        rows.append((key[0], key[1], status, sizes(s), sizes(c), len(s), len(c)))
    report = args.out / "layout-status.tsv"
    with report.open("w", newline="") as f:
        w = csv.writer(f, delimiter="\t")
        w.writerow(["kind","name","status","stock_sizes","candidate_sizes",
                    "stock_variants","candidate_variants"])
        w.writerows(rows)
    critical = ("task_struct","cred","file","module","f2fs_sb_info",
                "f2fs_inode_info","f2fs_checkpoint","defex_context",
                "super_block","inode","dentry")
    summary = {
        "stock_named_types": len(stock),
        "candidate_named_types": len(candidate),
        "compared_types": len(rows),
        "status_counts": dict(Counter(r[2] for r in rows)),
        "critical": {name: [
            {"status": r[2], "stock_bytes": r[3], "candidate_bytes": r[4]}
            for r in rows if r[1] == name] for name in critical},
        "limitations": [
            "Match covers named outer struct/union sizes, all named member "
            "names, offsets, bitfields, and human-readable member types.",
            "Nested/anonymous transitive type graphs and function bodies "
            "are not fully normalized by this TSV-level comparator.",
            "BTF cannot establish Module.symvers CRC identity, kernel "
            "exports, signature trust, security policy or loadability.",
        ],
    }
    (args.out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
